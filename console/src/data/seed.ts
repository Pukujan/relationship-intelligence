const NOW = new Date();

const iso = (date: Date) => date.toISOString();

const minutesAgo = (minutes: number) =>
  iso(new Date(NOW.getTime() - minutes * 60_000));

const hoursAgo = (hours: number) => minutesAgo(hours * 60);

const daysAgo = (days: number, hour = 10, minute = 0) => {
  const date = new Date(NOW);
  date.setDate(date.getDate() - days);
  date.setHours(hour, minute, 0, 0);
  return iso(date);
};

const inDays = (days: number, hour = 18, minute = 0) => {
  const date = new Date(NOW);
  date.setDate(date.getDate() + days);
  date.setHours(hour, minute, 0, 0);
  return iso(date);
};

const warmthOf = (strength: number): Warmth => {
  if (strength >= 80) return "hot";
  if (strength >= 60) return "warm";
  if (strength >= 40) return "cool";
  return "cold";
};

